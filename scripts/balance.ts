// Scores every rollable player-season and writes docs/balance-report.md.
// Every season is equally likely to be rolled, so these distributions are
// exactly the distribution of daily roll scores.
//
//   npm run balance

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { loadSeasons } from "../src/lib/data/seasons";
import type { PlayerSeason } from "../src/lib/data/types";
import { BADGES, SCORING_VERSION, scoreSeason, type ScoreResult } from "../src/lib/scoring";

interface Scored {
  season: PlayerSeason;
  result: ScoreResult;
}

const scored: Scored[] = [...loadSeasons().values()].flat().map((season) => ({ season, result: scoreSeason(season) }));
const totals = scored.map((s) => s.result.total).sort((a, b) => a - b);
const n = totals.length;

const quantile = (sorted: number[], q: number) => sorted[Math.min(sorted.length - 1, Math.floor(q * sorted.length))];
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
const fmt = (x: number) => Math.round(x).toLocaleString("en-US");
const pctOf = (k: number, of: number) => `${((100 * k) / of).toFixed(1)}%`;
const label = (s: Scored) =>
  `${s.season.year} ${s.season.name} (#${s.season.ranking.final})`;

const lines: string[] = [];
const out = (...l: string[]) => lines.push(...l);

out(
  "# Balance report",
  "",
  `Generated by \`npm run balance\` with scoring version ${SCORING_VERSION}. ${fmt(n)} player-seasons,`,
  "each equally likely to be rolled, so this is the distribution of daily roll scores.",
  "",
  "## Score distribution",
  "",
  "| min | p10 | p25 | median | p75 | p90 | p99 | max | mean |",
  "|---|---|---|---|---|---|---|---|---|",
  `| ${[0, 0.1, 0.25, 0.5, 0.75, 0.9, 0.99].map((q) => fmt(quantile(totals, q))).join(" | ")} | ${fmt(totals[n - 1])} | ${fmt(mean(totals))} |`,
  "",
);

const buckets: Array<[number, number]> = [
  [0, 10_000],
  [10_000, 25_000],
  [25_000, 50_000],
  [50_000, 100_000],
  [100_000, 250_000],
  [250_000, 1_000_000],
  [1_000_000, 5_000_000],
  [5_000_000, 25_000_000],
  [25_000_000, Infinity],
];
out("| score | share of rolls | about 1 in |", "|---|---|---|");
for (const [lo, hi] of buckets) {
  const k = totals.filter((t) => t >= lo && t < hi).length;
  out(`| ${fmt(lo)}${hi === Infinity ? "+" : `–${fmt(hi - 1)}`} | ${pctOf(k, n)} | ${k ? fmt(n / k) : "—"} |`);
}

out("", "## By final rank", "", "| rank | median | mean | max |", "|---|---|---|---|");
const rankBands: Array<[number, number]> = [
  [1, 1],
  [2, 5],
  [6, 10],
  [11, 20],
  [21, 50],
  [51, 100],
];
for (const [lo, hi] of rankBands) {
  const band = scored
    .filter((s) => s.season.ranking.final >= lo && s.season.ranking.final <= hi)
    .map((s) => s.result.total)
    .sort((a, b) => a - b);
  out(`| ${lo === hi ? `#${lo}` : `#${lo}–${hi}`} | ${fmt(quantile(band, 0.5))} | ${fmt(mean(band))} | ${fmt(band[band.length - 1])} |`);
}

const byTotal = [...scored].sort((a, b) => b.result.total - a.result.total);
const row = (s: Scored) =>
  `| ${label(s)} | ${fmt(s.result.base)} | ×${s.result.multiplier.toFixed(1)} | **${fmt(s.result.total)}** | ${s.result.badges.length} |`;
out("", "## Top 25 seasons", "", "| season | base | mult | total | badges |", "|---|---|---|---|---|");
byTotal.slice(0, 25).forEach((s) => out(row(s)));
out("", "## Bottom 10 seasons", "", "| season | base | mult | total | badges |", "|---|---|---|---|---|");
byTotal.slice(-10).forEach((s) => out(row(s)));

out(
  "",
  "## Badges",
  "",
  "How often each badge fires, its average value when earned, and its share of all base points.",
  "",
  "| badge | earned by | about 1 in | avg when earned | share of points |",
  "|---|---|---|---|---|",
);
const allBase = scored.reduce((a, s) => a + s.result.base, 0);
for (const def of BADGES) {
  const hits = scored.flatMap((s) => s.result.badges.filter((b) => b.id === def.id));
  if (hits.length === 0) {
    out(`| ${def.name} | never | — | — | — |`);
    continue;
  }
  const isMult = hits[0].multiplier !== null;
  const avg = isMult ? `×${mean(hits.map((h) => h.multiplier!)).toFixed(2)}` : fmt(mean(hits.map((h) => h.points)));
  const share = isMult ? "—" : pctOf(hits.reduce((a, h) => a + h.points, 0), allBase);
  out(`| ${def.name} | ${pctOf(hits.length, n)} | ${fmt(n / hits.length)} | ${avg} | ${share} |`);
}

const docs = join(import.meta.dirname, "../docs");
mkdirSync(docs, { recursive: true });
writeFileSync(join(docs, "balance-report.md"), `${lines.join("\n")}\n`);
